import { useMemo, useState } from 'react'
import { ToolLayout } from '../../components/ToolLayout'
import { Segmented } from '../../components/Segmented'
import { useCopied } from '../../lib/useCopied'
import { agreementText, billOfSale, businessCardSvg, resumeText, signatureHtml } from '../../lib/stationery'
import { triggerDownload } from '../../lib/download'

type Mode = 'resume' | 'signature' | 'card' | 'bill' | 'agreement'

export default function StationeryTool() {
  const [mode, setMode] = useState<Mode>('resume')
  const [name, setName] = useState('')
  const [title, setTitle] = useState('')
  const [email, setEmail] = useState('')
  const [phone, setPhone] = useState('')
  const [company, setCompany] = useState('')
  const [website, setWebsite] = useState('')
  const [summary, setSummary] = useState('')
  const [experience, setExperience] = useState('')
  const [education, setEducation] = useState('')
  const [seller, setSeller] = useState('')
  const [buyer, setBuyer] = useState('')
  const [item, setItem] = useState('')
  const [price, setPrice] = useState('')
  const [date, setDate] = useState('')
  const [notes, setNotes] = useState('')
  const [partyA, setPartyA] = useState('')
  const [partyB, setPartyB] = useState('')
  const [subject, setSubject] = useState('')
  const [terms, setTerms] = useState('')
  const { copied, copy } = useCopied()

  const output = useMemo(() => {
    if (mode === 'resume') return resumeText({ name, title, email, phone, summary, experience, education })
    if (mode === 'signature') return signatureHtml({ name, title, company, email, phone, website })
    if (mode === 'card') return businessCardSvg({ name, title, company, email, phone })
    if (mode === 'bill') return billOfSale({ seller, buyer, item, price, date, notes })
    return agreementText({ partyA, partyB, date, subject, terms })
  }, [
    mode,
    name,
    title,
    email,
    phone,
    company,
    website,
    summary,
    experience,
    education,
    seller,
    buyer,
    item,
    price,
    date,
    notes,
    partyA,
    partyB,
    subject,
    terms,
  ])

  const field = (label: string, value: string, set: (value: string) => void) => (
    <label className="field" key={label}>
      <span>{label}</span>
      <input className="text-input" value={value} onChange={(e) => set(e.target.value)} />
    </label>
  )

  return (
    <ToolLayout
      title="Print templates"
      lede="A resume, an email signature, a business card, a bill of sale, and a short agreement. You fill them in. Nothing is generated by a model."
    >
      <Segmented
        label="Template"
        value={mode}
        onChange={setMode}
        options={[
          { value: 'resume', label: 'Resume' },
          { value: 'signature', label: 'Signature' },
          { value: 'card', label: 'Card' },
          { value: 'bill', label: 'Bill of sale' },
          { value: 'agreement', label: 'Agreement' },
        ]}
      />
      {mode === 'resume' || mode === 'signature' || mode === 'card' ? (
        <div className="stack">
          {field('Name', name, setName)}
          {field('Title', title, setTitle)}
          {mode !== 'resume' ? field('Company', company, setCompany) : null}
          {field('Email', email, setEmail)}
          {field('Phone', phone, setPhone)}
          {mode === 'signature' ? field('Website', website, setWebsite) : null}
        </div>
      ) : null}
      {mode === 'resume' ? (
        <>
          <label className="field">
            <span>Summary</span>
            <textarea className="code-area" rows={3} value={summary} onChange={(e) => setSummary(e.target.value)} />
          </label>
          <label className="field">
            <span>Experience</span>
            <textarea
              className="code-area"
              rows={4}
              value={experience}
              onChange={(e) => setExperience(e.target.value)}
            />
          </label>
          <label className="field">
            <span>Education</span>
            <textarea className="code-area" rows={3} value={education} onChange={(e) => setEducation(e.target.value)} />
          </label>
        </>
      ) : null}
      {mode === 'bill' ? (
        <div className="stack">
          {field('Date', date, setDate)}
          {field('Seller', seller, setSeller)}
          {field('Buyer', buyer, setBuyer)}
          {field('Item', item, setItem)}
          {field('Price', price, setPrice)}
          <label className="field">
            <span>Notes</span>
            <textarea className="code-area" rows={3} value={notes} onChange={(e) => setNotes(e.target.value)} />
          </label>
        </div>
      ) : null}
      {mode === 'agreement' ? (
        <div className="stack">
          {field('Date', date, setDate)}
          {field('First party', partyA, setPartyA)}
          {field('Second party', partyB, setPartyB)}
          {field('Subject', subject, setSubject)}
          <label className="field">
            <span>Terms</span>
            <textarea className="code-area" rows={5} value={terms} onChange={(e) => setTerms(e.target.value)} />
          </label>
        </div>
      ) : null}
      {mode === 'signature' ? <div dangerouslySetInnerHTML={{ __html: output }} /> : null}
      {mode === 'card' ? <img alt="Business card" src={`data:image/svg+xml,${encodeURIComponent(output)}`} /> : null}
      {mode !== 'signature' && mode !== 'card' ? (
        <textarea className="code-area" rows={12} readOnly value={output} />
      ) : null}
      <div className="row">
        <button type="button" className="btn btn-primary" onClick={() => void copy(output, 'doc')}>
          {copied === 'doc' ? 'Copied ✓' : 'Copy'}
        </button>
        <button
          type="button"
          className="btn"
          onClick={() =>
            triggerDownload(
              new Blob([output], {
                type: mode === 'card' ? 'image/svg+xml' : mode === 'signature' ? 'text/html' : 'text/plain',
              }),
              mode === 'card' ? 'card.svg' : mode === 'signature' ? 'signature.html' : `${mode}.txt`,
            )
          }
        >
          Download
        </button>
      </div>
    </ToolLayout>
  )
}
